-- db-test: run-as=app_server
-- Custom roles (FR-IAM-07, EP-ROLES; PO 17 Oct 2026; migrations 20261019090000…090400). Runs CONNECTED AS
-- app_server. Who builds roles (only the Organization Admin, platform.role.manage), which permissions a role
-- may carry (catalogue only, held by the builder, administrative ones organization-wide only), unique names,
-- delete only when nobody holds it, privileged = any high-risk permission, and the database guards deciding
-- by PERMISSION for holders of custom roles (invite, give roles, organization profile, security policy).
-- Tenant A: uA = Organization Admin, uAB = HR Manager, uM (…f7, 35) = active member without a role.
-- Custom roles of the fixtures: A «Course reviewer» (custom_a00000000001: user.read, org.read; organization),
-- B «Reviewer» (custom_b00000000001: user.read; team).
\set ON_ERROR_STOP on

do $$ begin perform tests.assert(session_user = 'app_server', 'must run connected as app_server'); end $$;

-- ---------------------------------------------------------------------------------------------------
-- The Organization Admin builds roles.
-- ---------------------------------------------------------------------------------------------------
begin;
set local role authenticated;
select tests.set_claims(tests.user_claims('00000000-0000-4000-8000-0000000000a1', '10000000-0000-4000-8000-0000000000a1',
  'a0000000-0000-4000-8000-000000000001', 'a1000000-0000-4000-8000-0000000000a1'));
do $$
declare
  v_role platform.custom_roles;
  v_id constant uuid := 'a6000000-0000-4000-8000-0000000000e1';
  v_team constant uuid := 'a6000000-0000-4000-8000-0000000000e2';
begin
  insert into platform.custom_roles (id, name_en, name_ar, description, data_scope)
  values (v_id, 'Finance approver', 'معتمد مالي', 'Approves cost.', 'organization');
  select * into v_role from platform.custom_roles where id = v_id;
  perform tests.assert(v_role.code ~ '^custom_[0-9a-f]{12}$', 'the code is generated by the database');
  perform tests.assert_eq(row(v_role.tenant_id, v_role.created_by, v_role.version)::text,
    row('a0000000-0000-4000-8000-000000000001'::uuid, 'a1000000-0000-4000-8000-0000000000a1'::uuid, 1)::text,
    'tenant from the claims, stamped with the actor, version 1');
  perform tests.assert_privilege_denied($q$insert into platform.custom_roles (code, name_en, name_ar, data_scope) values ('custom_0123456789ab', 'Mine', 'لي', 'own')$q$,
    'the code is never chosen by the request');
  perform tests.assert_privilege_denied(format($q$update platform.custom_roles set code = 'custom_0123456789ab' where id = %L$q$, v_id),
    'the code never changes');

  -- Names: unique in the organization, case-insensitive, trimmed.
  perform tests.assert_fails($q$insert into platform.custom_roles (name_en, name_ar, data_scope) values ('FINANCE APPROVER', 'آخر', 'own')$q$,
    array['23505'], 'English names are unique in the organization (case-insensitive)');
  perform tests.assert_fails($q$insert into platform.custom_roles (name_en, name_ar, data_scope) values ('Other', 'معتمد مالي', 'own')$q$,
    array['23505'], 'Arabic names are unique in the organization');
  perform tests.assert_check_constraint($q$insert into platform.custom_roles (name_en, name_ar, data_scope) values (' Padded', 'مسافة', 'own')$q$,
    'custom_roles_name_en_check', 'names are trimmed');
  perform tests.assert_check_constraint($q$insert into platform.custom_roles (name_en, name_ar, data_scope) values ('Scope', 'نطاق', 'branch')$q$,
    'custom_roles_data_scope_check', 'one of the four data scopes');
  perform tests.assert_eq(tests.rows_affected($q$insert into platform.custom_roles (name_en, name_ar, data_scope) values ('Course reviewer B', 'مراجع', 'own')$q$),
    1::bigint, 'the same name in another organization does not collide («مراجع» is tenant B''s)');

  -- Permissions: from the catalogue, held by the builder.
  perform tests.assert_eq(tests.rows_affected(format($q$insert into platform.custom_role_permissions (custom_role_id, permission_code) values (%L, 'platform.user.read'), (%L, 'platform.role.read')$q$, v_id, v_id)),
    2::bigint, 'permissions the Organization Admin holds');
  perform tests.assert(not private.role_is_privileged('a0000000-0000-4000-8000-000000000001', v_role.code),
    'no high-risk permission: an ordinary role');
  perform tests.assert_eq(tests.rows_affected(format($q$insert into platform.custom_role_permissions (custom_role_id, permission_code) values (%L, 'platform.audit.read')$q$, v_id)),
    1::bigint, 'a high-risk permission');
  perform tests.assert(private.role_is_privileged('a0000000-0000-4000-8000-000000000001', v_role.code),
    'a high-risk permission makes the role privileged (computed)');
  perform tests.assert_fails_like(format($q$insert into platform.custom_role_permissions (custom_role_id, permission_code) values (%L, 'platform.role.assign_privileged')$q$, v_id),
    'permission platform.role.assign_privileged cannot be part of a custom role', 'the Organization Admin''s own permission never');
  perform tests.assert_fails_like(format($q$insert into platform.custom_role_permissions (custom_role_id, permission_code) values (%L, 'platform.role.manage')$q$, v_id),
    'permission platform.role.manage cannot be part of a custom role', 'building roles never');
  perform tests.assert_fails_like(format($q$insert into platform.custom_role_permissions (custom_role_id, permission_code) values (%L, 'platform.org.manage')$q$, v_id),
    'nobody can give a permission they do not hold (platform.org.manage)', 'a permission the builder does not hold (the structure is HR''s)');
  perform tests.assert_fails(format($q$insert into platform.custom_role_permissions (custom_role_id, permission_code) values (%L, 'tms.session.read')$q$, v_id),
    array['42501'], 'a permission outside the catalogue');
  perform tests.assert_privilege_denied($q$update platform.custom_role_permissions set permission_code = 'platform.org.read'$q$,
    'permissions are removed and added, never rewritten');

  -- Administrative permissions only organization-wide.
  insert into platform.custom_roles (id, name_en, name_ar, data_scope) values (v_team, 'Team lead', 'قائد فريق', 'team');
  perform tests.assert_eq(tests.rows_affected(format($q$insert into platform.custom_role_permissions (custom_role_id, permission_code) values (%L, 'platform.user.read'), (%L, 'platform.org.read')$q$, v_team, v_team)),
    2::bigint, 'reading people (their team) and the structure');
  perform tests.assert_fails(format($q$insert into platform.custom_role_permissions (custom_role_id, permission_code) values (%L, 'platform.user.invite')$q$, v_team),
    array['JR003'], 'an administrative permission needs the whole organization as scope');
  perform tests.assert_eq(tests.rows_affected(format($q$update platform.custom_roles set data_scope = 'own' where id = %L$q$, v_team)),
    1::bigint, 'a role without administrative permissions changes its scope');
  perform tests.assert_fails(format($q$update platform.custom_roles set data_scope = 'team' where id = %L$q$, v_id),
    array['JR003'], 'a role with an administrative permission (audit log) keeps the whole organization');
  perform tests.assert_eq((select version from platform.custom_roles where id = v_team), 2,
    'a change bumps the version (optimistic concurrency)');
end $$;
reset role;
rollback;

-- Delete only when nobody holds it (members and pending invitations), with the numbers.
begin;
set local role authenticated;
select tests.set_claims(tests.user_claims('00000000-0000-4000-8000-0000000000a1', '10000000-0000-4000-8000-0000000000a1',
  'a0000000-0000-4000-8000-000000000001', 'a1000000-0000-4000-8000-0000000000a1'));
insert into platform.persons (id, display_name_ar, email) values ('a1000000-0000-4000-8000-0000000000d9', 'مدعو بدور', 'cr@a.test');
do $$
declare
  v_m uuid := (select id from platform.tenant_memberships where user_id = '00000000-0000-4000-8000-0000000000f7' and tenant_id = 'a0000000-0000-4000-8000-000000000001');
begin
  insert into platform.role_assignments (membership_id, role_code) values (v_m, 'custom_a00000000001');
  begin
    delete from platform.custom_roles where code = 'custom_a00000000001';
    raise exception 'ASSERTION FAILED: a role held by a member was deleted';
  exception when sqlstate 'JR002' then
    perform tests.assert_eq(sqlerrm, 'the role is still held: 1 member(s), 0 pending invitation(s)',
      'a role held by a member is not deleted (JR002, with the numbers)');
  end;
  delete from platform.role_assignments where membership_id = v_m;
  insert into platform.invitations (person_id, email, locale, primary_role) values
    ('a1000000-0000-4000-8000-0000000000d9', 'cr@a.test', 'ar', 'custom_a00000000001');
  perform tests.assert_fails($q$delete from platform.custom_roles where code = 'custom_a00000000001'$q$,
    array['JR002'], 'a role named by a pending invitation is not deleted');
  update platform.invitations set status = 'revoked' where person_id = 'a1000000-0000-4000-8000-0000000000d9';
  perform tests.assert_eq(tests.rows_affected($q$delete from platform.custom_roles where code = 'custom_a00000000001'$q$),
    1::bigint, 'nobody holds it: deleted');
  perform tests.assert_eq((select count(*) from platform.custom_role_permissions where custom_role_id = 'a6000000-0000-4000-8000-000000000001'),
    0::bigint, 'its permissions go with it');
  perform tests.assert_fails($q$insert into platform.invitations (person_id, email, locale, primary_role) values ('a1000000-0000-4000-8000-0000000000d9', 'cr@a.test', 'ar', 'custom_a00000000001')$q$,
    array['23503'], 'a deleted custom role cannot be given');
  perform tests.assert_fails($q$insert into platform.invitations (person_id, email, locale, primary_role) values ('a1000000-0000-4000-8000-0000000000d9', 'cr@a.test', 'ar', 'custom_b00000000001')$q$,
    array['23503'], 'another organization''s custom role cannot be given');
end $$;
reset role;
rollback;

