/**
 * File purposes (ADR 0006 §1; T-M2-18). The DATABASE is the authority (platform.file_purposes, migration
 * 20261015090000: create_file_upload and the scan apply its limits); this mirror lets the request path
 * refuse early and pick the canonical declared type. An integration test keeps both identical. Modules add
 * a purpose here AND in their own migration.
 */
export const XLSX = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';

export type RetentionClass = 'import' | 'owner_lifetime' | 'record' | 'export';

export interface PurposeDefinition {
  readonly bucket: 'materials' | 'images' | 'evidence' | 'imports' | 'generated';
  readonly maxBytes: number;
  /** Types accepted after detection by content. */
  readonly types: readonly string[];
  readonly retention: RetentionClass;
  /** `user`: uploaded by a person (scanned); `worker`: generated by a job (stored clean). */
  readonly uploadBy: 'user' | 'worker';
  readonly auditDownloads: boolean;
  readonly downloadTtlSeconds: number;
}

const MB = 1024 * 1024;

export const FILE_PURPOSES = {
  /** Bulk user import (T-M2-12, FR-IAM-04): CSV (UTF-8) or XLSX, 20 MB. */
  'platform.user_import': {
    bucket: 'imports',
    maxBytes: 20 * MB,
    types: ['text/csv', XLSX],
    retention: 'import',
    uploadBy: 'user',
    auditDownloads: true,
    downloadTtlSeconds: 60,
  },
  /** The import's error report, written by the import job (T-M2-12). */
  'platform.user_import_report': {
    bucket: 'generated',
    maxBytes: 50 * MB,
    types: ['text/csv'],
    retention: 'import',
    uploadBy: 'worker',
    auditDownloads: true,
    downloadTtlSeconds: 60,
  },
  /** Profile photo (T-M2-15b, FR-IAM-16): PNG, JPEG or WebP — never SVG or GIF. */
  'platform.profile_photo': {
    bucket: 'images',
    maxBytes: 10 * MB,
    types: ['image/png', 'image/jpeg', 'image/webp'],
    retention: 'owner_lifetime',
    uploadBy: 'user',
    auditDownloads: false,
    downloadTtlSeconds: 300,
  },
} as const satisfies Record<string, PurposeDefinition>;

export type FilePurpose = keyof typeof FILE_PURPOSES;

/** Purposes people upload (the others are written by jobs). */
export type UploadPurpose = {
  [P in FilePurpose]: (typeof FILE_PURPOSES)[P]['uploadBy'] extends 'user' ? P : never;
}[FilePurpose];

/** Purposes jobs write (generated files). */
export type GeneratedPurpose = Exclude<FilePurpose, UploadPurpose>;

export function isFilePurpose(value: string): value is FilePurpose {
  return Object.hasOwn(FILE_PURPOSES, value);
}

export function purposeOf(purpose: FilePurpose): PurposeDefinition {
  return FILE_PURPOSES[purpose];
}

/** The canonical type for a file extension (lower-case, with the dot). */
const BY_EXTENSION: Readonly<Record<string, string>> = {
  '.csv': 'text/csv',
  '.xlsx': XLSX,
  '.png': 'image/png',
  '.jpg': 'image/jpeg',
  '.jpeg': 'image/jpeg',
  '.webp': 'image/webp',
  '.pdf': 'application/pdf',
};

/** Types browsers report for the same files (Windows reports CSV as an Excel type, some report nothing). */
const ALIASES: Readonly<Record<string, string>> = {
  'application/vnd.ms-excel': 'text/csv',
  'text/comma-separated-values': 'text/csv',
  'application/csv': 'text/csv',
  'text/x-csv': 'text/csv',
  'image/jpg': 'image/jpeg',
  'image/pjpeg': 'image/jpeg',
};

function extensionOf(name: string): string {
  const dot = name.lastIndexOf('.');
  return dot <= 0 ? '' : name.slice(dot).toLowerCase();
}

/**
 * The declared type to record and to send as the upload's Content-Type: from the file's extension when it
 * names a type the purpose accepts, else the browser's type (aliases resolved) when the purpose accepts
 * it; null when neither does (refused before anything is stored). Declared types are a first filter only:
 * the scan detects the real type by content.
 */
export function normalizeDeclaredType(
  purpose: FilePurpose,
  name: string,
  browserType: string | null | undefined,
): string | null {
  const allowed: readonly string[] = FILE_PURPOSES[purpose].types;
  const byExtension = BY_EXTENSION[extensionOf(name)];
  if (byExtension !== undefined) return allowed.includes(byExtension) ? byExtension : null;
  const reported = (browserType ?? '').trim().toLowerCase();
  const canonical = ALIASES[reported] ?? reported;
  return allowed.includes(canonical) ? canonical : null;
}
