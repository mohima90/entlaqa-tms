  ('a6000000-0000-4000-8000-0000000000e4', 'platform.user.read'),
  ('a6000000-0000-4000-8000-0000000000e4', 'platform.org.read');
insert into platform.role_assignments (membership_id, role_code)
select m.id, cr.code from platform.tenant_memberships m, platform.custom_roles cr
where m.user_id = '00000000-0000-4000-8000-0000000000f7' and m.tenant_id = 'a0000000-0000-4000-8000-000000000001'
  and cr.id = 'a6000000-0000-4000-8000-0000000000e4';
do $$
begin
  perform tests.assert_eq(private.member_permissions('a0000000-0000-4000-8000-000000000001', '00000000-0000-4000-8000-0000000000f7'),
    array['platform.org.read'], 'team scope: only the organization-wide permission counts organization-wide');
  perform tests.assert(not private.role_is_privileged('a0000000-0000-4000-8000-000000000001',
                         (select code from platform.custom_roles where id = 'a6000000-0000-4000-8000-0000000000e4')),
    'reading only: an ordinary role (the HR Manager may give it)');
