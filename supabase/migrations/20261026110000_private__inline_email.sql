-- E-mail sent the moment the action commits (WP-ADM-05 follow-up; PO 23 Oct 2026: "every e-mail arrives
-- immediately", the Kawadir way). Class: T (platform.message_deliveries) + P. PII: the delivery log's usual
-- rules (content and plain address only while the message waits).
--
-- The flow: the web action queues the delivery INSIDE its own transaction (a row in the delivery log, content
-- rendered by the web app) and, once the response is out (`after()`), CLAIMS it with the secret only that
-- request holds, sends it through the sender rule and records the outcome. The worker stays the safety net:
-- a row nobody finished within a minute is queued for the worker's sender (rescue), and the worker's own
-- mailers skip a message the web already queued (source_key). Claiming is ONE shared lease for both senders
-- (status `sending` + updated_at, 5 minutes), so a message goes out once whoever gets it.
--
-- Security shape (nothing broader than the request that queued the message):
--   * The web app cannot read or claim the delivery log: only these functions can (owner inline_mail_guard,
--     a role of its own, no BYPASSRLS, explicit grants and policies below).
--   * A message is queued only for a KIND the function knows, which re-checks the caller's authority and that
--     the destination is the address the kind implies (an invitation's own address, …).
--   * The queue returns nothing the caller can use to claim anybody else's message: the claim needs the random
--     secret generated by the request that queued it (only its SHA-256 is stored; removed when the message is
--     final).
--   * The sender settings (sealed provider secrets) are returned only together with a successful claim.
-- Functions:
--   private.inline_invitation_prepare(invitation)   web app, user claims: what the invitation e-mail needs
--   private.inline_mail_queue(kind, ref, …)          web app, user claims: queues one message (null: that
--                                                    message was queued already)
--   private.inline_mail_claim(id, secret)            web app: claim + the sender settings
--   private.inline_mail_finish(id, secret, …)       web app: the outcome
--   private.inline_mail_tenants_to_rescue()          worker platform task
-- Expand-first: new column, role and functions only.

-- ---------------------------------------------------------------------------------------------------
-- Role inline_mail_guard (attribute policy as in 20260930120000)
-- ---------------------------------------------------------------------------------------------------
do $$
begin
  if not exists (select 1 from pg_roles where rolname = 'inline_mail_guard') then
    create role inline_mail_guard nologin noinherit nobypassrls;
  end if;
end
$$;

do $$
declare
  r record;
begin
  select rolname, rolcanlogin, rolinherit, rolsuper, rolbypassrls, rolreplication, rolcreatedb, rolcreaterole
    into r from pg_roles where rolname = 'inline_mail_guard';
  if r.rolsuper or r.rolbypassrls or r.rolreplication then
    raise exception 'role inline_mail_guard must be NOSUPERUSER NOBYPASSRLS NOREPLICATION; fix it as a superuser first';
  end if;
  if r.rolinherit or r.rolcreatedb or r.rolcreaterole or r.rolcanlogin then
    alter role inline_mail_guard nologin noinherit nocreatedb nocreaterole;
  end if;
  if exists (select 1 from pg_auth_members m join pg_roles g on g.oid = m.roleid join pg_roles u on u.oid = m.member
             where g.rolname = 'inline_mail_guard' and (m.inherit_option or m.set_option)
               and not u.rolsuper and u.rolname <> current_user) then
    raise exception 'role inline_mail_guard must have no members besides the migration role';
  end if;
end
$$;

