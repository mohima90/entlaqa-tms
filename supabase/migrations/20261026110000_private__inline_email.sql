-- ---------------------------------------------------------------------------------------------------
-- The caller: a signed-in member of an organization, through the web app's login role
-- ---------------------------------------------------------------------------------------------------
create or replace function private.inline_mail_caller(out o_user uuid, out o_tenant uuid)
language plpgsql stable
set search_path = ''
as $$
declare
  v_claims jsonb := private.request_claims();
begin
  if session_user <> 'app_server' or v_claims is null or coalesce(v_claims ->> 'role', '') <> 'authenticated' then
    raise exception 'inline e-mail needs a signed-in member' using errcode = 'insufficient_privilege';
  end if;
  o_user := private.request_user_id();
  o_tenant := private.current_tenant_id();
  if o_user is null or o_tenant is null then
    raise exception 'inline e-mail needs a signed-in member of an organization' using errcode = 'insufficient_privilege';
  end if;
end
$$;
comment on function private.inline_mail_caller() is
  'SECURITY-RELEVANT. The verified user and organization of an app_server request, or 42501. Internal to inline_mail_guard''s functions.';

-- ---------------------------------------------------------------------------------------------------
-- Invitation e-mail: the facts, for a caller who may manage the invitation
-- ---------------------------------------------------------------------------------------------------
create or replace function private.inline_invitation_prepare(p_invitation_id uuid)
returns table (invitation_id uuid, send_count integer, email text, locale text, person_id uuid, invite_code text,
               recipient_ar text, recipient_en text, inviter_ar text, inviter_en text, organization_ar text,
               organization_en text, primary_role text, role_name_ar text, role_name_en text, expires_at timestamptz,
               source_key text, action_color text, link_color text, logo_asset_id uuid)
language plpgsql stable security definer
set search_path = ''
as $$
declare
  v_user uuid;
  v_tenant uuid;
  v_code text;
begin
  select c.o_user, c.o_tenant into v_user, v_tenant from private.inline_mail_caller() c;
  -- The authority check is the one behind «copy the code»: pending, sent, unexpired, caller may manage it.
  select c.invite_code into v_code from private.invitation_codes(array[p_invitation_id]) c
  where c.invitation_id = p_invitation_id;
  if v_code is null then
    return;
  end if;
  return query
    select i.id, i.send_count::integer, i.email, i.locale, i.person_id, v_code,
           coalesce(p.display_name_ar, p.display_name_en), p.display_name_en,
           coalesce(ip.display_name_ar, ip.display_name_en), ip.display_name_en,
           t.name_ar, t.name_en, i.primary_role, cr.name_ar, cr.name_en, i.expires_at,
           'invitation:' || i.id::text || ':' || i.send_count::text,
           r.action_color, r.link_color, r.logo_asset_id
    from platform.invitations i
    join platform.persons p on p.tenant_id = i.tenant_id and p.id = i.person_id
    join platform.tenants t on t.id = i.tenant_id
    left join platform.tenant_memberships m on m.tenant_id = i.tenant_id and m.user_id = v_user
    left join platform.persons ip on ip.tenant_id = m.tenant_id and ip.id = m.person_id
    left join platform.custom_roles cr on cr.tenant_id = i.tenant_id and cr.code = i.primary_role
    left join lateral (select x.action_color, x.link_color, x.logo_asset_id
                       from private.auth_mail_route(i.tenant_id) x) r on true
    where i.id = p_invitation_id and i.tenant_id = v_tenant and i.status = 'pending' and not i.mail_held
      and i.send_count >= 1;
end
$$;
comment on function private.inline_invitation_prepare(uuid) is
  'SECURITY-RELEVANT (WP-ADM-05 follow-up). The facts and the current code of an invitation the signed-in caller may manage, for the e-mail the web app sends at once. app_server user claims only.';

-- ---------------------------------------------------------------------------------------------------
-- Queue one message (inside the action's transaction)
-- ---------------------------------------------------------------------------------------------------
create or replace function private.inline_mail_queue(p_kind text, p_ref uuid, p_template text, p_version integer,
                                                      p_locale text, p_to text, p_subject text, p_html text,
                                                      p_text text, p_source_key text, p_claim_hash bytea)
returns uuid
language plpgsql volatile security definer
set search_path = ''
as $$
declare
  v_user uuid;
  v_tenant uuid;
  v_to text := lower(btrim(p_to));
  v_person uuid;
  v_inv record;
  v_id uuid;
begin
  select c.o_user, c.o_tenant into v_user, v_tenant from private.inline_mail_caller() c;
  if p_claim_hash is null or octet_length(p_claim_hash) <> 32 or v_to is null or p_source_key is null then
    raise exception 'invalid inline e-mail' using errcode = 'invalid_parameter_value';
  end if;
  if p_kind = 'invitation' then
    -- The invitation's own address, its own current code number, the invitation e-mail only, and a caller who
    -- may manage it (the check behind «copy the code»).
    select i.id, i.person_id, i.email, i.locale, i.send_count into v_inv
    from platform.invitations i
    where i.id = p_ref and i.tenant_id = v_tenant and i.status = 'pending' and not i.mail_held and i.send_count >= 1;
    if not found
       or p_template <> 'platform.invitation'
       or v_inv.email <> v_to
       or p_source_key <> 'invitation:' || v_inv.id::text || ':' || v_inv.send_count::text
       or not exists (select 1 from private.invitation_codes(array[p_ref]) c where c.invitation_id = p_ref) then
      raise exception 'this e-mail cannot be queued' using errcode = 'insufficient_privilege';
    end if;
    v_person := v_inv.person_id;
  else
    raise exception 'unknown inline e-mail kind' using errcode = 'invalid_parameter_value';
  end if;
  insert into platform.message_deliveries
    (tenant_id, template, template_version, locale, recipient_person_id, destination, destination_masked, subject,
     html_body, text_body, source_key, inline_claim_hash)
  values (v_tenant, p_template, p_version, p_locale, v_person, v_to,
          case when position('@' in v_to) > 1 then left(v_to, 1) || '***' || substr(v_to, position('@' in v_to))
               else '***' end,
          p_subject, p_html, p_text, p_source_key, p_claim_hash)
  on conflict (tenant_id, source_key) where source_key is not null do nothing
  returning id into v_id;
  return v_id;
end
$$;
comment on function private.inline_mail_queue(text, uuid, text, integer, text, text, text, text, text, text, bytea) is
  'SECURITY-RELEVANT (WP-ADM-05 follow-up). Queues one e-mail the web app will send at once, for a kind it knows, re-checking the caller''s authority and the destination. Returns null when the same message was queued already. app_server user claims only.';

-- ---------------------------------------------------------------------------------------------------
-- Claim (after the commit) and finish
-- ---------------------------------------------------------------------------------------------------
create or replace function private.inline_mail_claim(p_id uuid, p_secret bytea)
returns table (outcome text, tenant_id uuid, template text, destination text, subject text, html text, text_body text,
               attempts integer,
               tenant_provider text, tenant_options jsonb, tenant_credentials_sealed text, tenant_from_name text,
               tenant_from_address text, tenant_reply_to text, tenant_enabled boolean, tenant_version integer,
               platform_configured boolean, platform_provider text, platform_options jsonb,
               platform_credentials_sealed text, platform_from_address text, platform_verified boolean,
               platform_version integer, brand_name_ar text, brand_name_en text, default_locale text,
               action_color text, link_color text, logo_asset_id uuid)
language plpgsql volatile security definer
set search_path = ''
as $$
declare
  v_row record;
  r record;
begin
  if session_user <> 'app_server' then
    raise exception 'reserved to the web app' using errcode = 'insufficient_privilege';
  end if;
  if p_id is null or p_secret is null or octet_length(p_secret) <> 32 then
    outcome := 'gone';
    return next;
    return;
  end if;
  select d.id, d.tenant_id, d.template, d.status, d.updated_at into v_row
  from platform.message_deliveries d
  where d.id = p_id and d.inline_claim_hash = pg_catalog.sha256(p_secret)
  for update;
  if not found or v_row.status not in ('queued', 'sending') then
    outcome := 'gone';
    return next;
    return;
  end if;
  -- The shared lease: another sender (the worker's rescue) holds it for five minutes.
  if v_row.status = 'sending' and v_row.updated_at > now() - interval '300 seconds' then
    outcome := 'busy';
    return next;
    return;
  end if;
  -- A suspended or closed organization: nothing is sent; the worker's sender discards the message.
  select * into r from private.auth_mail_route(v_row.tenant_id);
  if not found then
    outcome := 'gone';
    return next;
    return;
  end if;
  return query
    with u as (
      update platform.message_deliveries d set status = 'sending', attempts = d.attempts + 1
      where d.id = v_row.id
      returning d.destination as d_destination, d.subject as d_subject, d.html_body as d_html,
                d.text_body as d_text, d.attempts as d_attempts)
    select 'claimed'::text, v_row.tenant_id, v_row.template, u.d_destination, u.d_subject, u.d_html, u.d_text,
           u.d_attempts::integer,
           r.tenant_provider, r.tenant_options, r.tenant_credentials_sealed, r.tenant_from_name,
           r.tenant_from_address, r.tenant_reply_to, r.tenant_enabled, r.tenant_version, r.platform_configured,
           r.platform_provider, r.platform_options, r.platform_credentials_sealed, r.platform_from_address,
           r.platform_verified, r.platform_version, r.brand_name_ar, r.brand_name_en, r.default_locale,
           r.action_color, r.link_color, r.logo_asset_id
    from u;
end
$$;
comment on function private.inline_mail_claim(uuid, bytea) is
  'SECURITY-RELEVANT (WP-ADM-05 follow-up). Claims a message queued by this request (it needs the request''s secret) for an immediate send, under the lease the worker''s sender shares, and returns it with the organization''s sender settings. app_server only.';

create or replace function private.inline_mail_finish(p_id uuid, p_secret bytea, p_status text, p_error_code text,
                                                        p_provider text, p_provider_message_id text, p_sender text)
returns boolean
language plpgsql volatile security definer
set search_path = ''
as $$
declare
  v_done integer;
begin
  if session_user <> 'app_server' then
    raise exception 'reserved to the web app' using errcode = 'insufficient_privilege';
  end if;
  if p_id is null or p_secret is null or octet_length(p_secret) <> 32
     or p_status not in ('sent', 'failed', 'retry') then
    raise exception 'invalid inline e-mail outcome' using errcode = 'invalid_parameter_value';
  end if;
  if p_status = 'retry' then
    -- Back to the queue with the reason (content kept): waits for a sender, or for the worker's rescue.
    update platform.message_deliveries d set status = 'queued', error_code = p_error_code
    where d.id = p_id and d.inline_claim_hash = pg_catalog.sha256(p_secret) and d.status = 'sending';
  else
    update platform.message_deliveries d
    set status = p_status, provider = p_provider,
        provider_message_id = case when p_status = 'sent' then p_provider_message_id else null end,
        error_code = case when p_status = 'sent' then null else p_error_code end,
        sent_at = case when p_status = 'sent' then now() else null end,
        sender = p_sender,
        destination = null, subject = null, html_body = null, text_body = null, inline_claim_hash = null
    where d.id = p_id and d.inline_claim_hash = pg_catalog.sha256(p_secret) and d.status = 'sending';
  end if;
  get diagnostics v_done = row_count;
  return v_done = 1;
end
$$;
comment on function private.inline_mail_finish(uuid, bytea, text, text, text, text, text) is
  'SECURITY-RELEVANT (WP-ADM-05 follow-up). Records the outcome of a claimed inline message (content, address and the secret''s hash removed when final). app_server only.';

-- ---------------------------------------------------------------------------------------------------
-- Safety net: organizations with inline messages nobody finished (worker platform task)
-- ---------------------------------------------------------------------------------------------------
create or replace function private.inline_mail_tenants_to_rescue()
returns table (tenant_id uuid)
language plpgsql stable security definer
set search_path = ''
as $$
declare
  v_claims jsonb := private.request_claims();
begin
  if session_user <> 'app_worker' or coalesce(v_claims ->> 'role', '') <> 'system' then
    raise exception 'reserved to the worker' using errcode = 'insufficient_privilege';
  end if;
  return query
    select distinct d.tenant_id
    from platform.message_deliveries d
    join platform.tenants t on t.id = d.tenant_id and t.status in ('active', 'trial')
    where d.inline_claim_hash is not null and d.created_at < now() - interval '60 seconds'
      and ((d.status = 'queued' and (d.error_code is null or not (d.error_code = any (private.email_waiting_codes()))))
           or (d.status = 'sending' and d.updated_at < now() - interval '300 seconds'))
      and (d.rescued_at is null or d.rescued_at < now() - interval '1 hour');
end
$$;
comment on function private.inline_mail_tenants_to_rescue() is
  'SECURITY-RELEVANT (WP-ADM-05 follow-up). Served organizations with inline messages unfinished for a minute: the worker queues them for its own sender. Worker platform tasks only.';

