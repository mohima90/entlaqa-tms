export const XLSX = 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet';

export type RetentionClass = 'import' | 'owner_lifetime' | 'record' | 'export';

export interface PurposeDefinition {
  readonly bucket: 'materials' | 'images' | 'evidence' | 'imports' | 'generated';
  readonly maxBytes: number;
  /** Types accepted after detection by content. */
  readonly types: readonly string[];
  readonly retention: RetentionClass;
  /** `user`: uploaded by a person (scanned); `worker`: generated by a job (stored clean). */
  readonly uploadBy: 'user' | 'worker';
  readonly auditDownloads: boolean;
  readonly downloadTtlSeconds: number;
}

